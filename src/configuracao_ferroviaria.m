function [C,referencia,E] = configuracao_ferroviaria(ajustes)
% Cada linha define símbolo, unidade e valores [referência, A, B].
arguments
    ajustes (1,1) struct = struct()
end
C.estatico = {'P','N',[1000 1500 2000]; 'k','N/m',[1e6 2e6 5e6]};
C.oscilador = {'m','kg',[450 1000 2000]; 'k','N/m',[2e7 1e7 4e7]; ...
    'c','N s/m',[2e4 1e4 4e4]};
C.contato = {'mv','kg',[250 500 1000]; 'kv','N/m',[1.5e7 1e7 3e7]; ...
    'cv','N s/m',[1.5e4 7.5e3 3e4]; 'kt','N/m',[2e7 1e7 4e7]; ...
    'a','m',[0.3e-3 0.6e-3 0.9e-3]; 'v','m/s',[15 22.5 30]; ...
    'd','m',[2 3 4]; 'mt','kg',450; 'ct','N s/m',2e4; ...
    'kH','N/m',1e9; 'rho','1',0.20; 'f0','Hz',12};
C.solo = {'r','m',[10 20 40]; 'alpha','1/m',[0.02 0.05 0.10]; ...
    'f0','Hz',[12 24 48]; 'P','N',[200 400 600]; 'H0','m/N',2e-9; ...
    'r0','m',1; 'fr','Hz',25; 'zeta','1',0.25; 'vs','m/s',200};
C.laje = {'m','kg',[5000 10000 20000]; 'k','N/m',[2e7 1e7 4e7]; ...
    'c','N s/m',[8e4 4e4 1.6e5]; 'P','N',[1000 500 2000]};
C.edificio = {'mb','kg',[5000 10000 20000]; 'kb','N/m',2e7; ...
    'cb','N s/m',8e4; 'ks','N/m',5e7; 'cs','N s/m',1e5; 'u0','m',0.02e-3};
% Aplique os valores da chamada antes de montar os casos de referência.
for grupo = fieldnames(ajustes).'
    tipo = grupo{1};
    assert(isfield(C,tipo),'Grupo de parâmetros desconhecido: %s.',tipo);
    alteracoes = ajustes.(tipo);
    validateattributes(alteracoes,{'struct'},{'scalar'});
    dados = C.(tipo);
    for campo = fieldnames(alteracoes).'
        nome = campo{1};
        linha = find(strcmp(dados(:,1),nome));
        assert(~isempty(linha),'Parâmetro desconhecido: %s.%s.',tipo,nome);
        valores = alteracoes.(nome);
        validateattributes(valores,{'numeric'}, ...
            {'vector','real','finite','numel',numel(dados{linha,3})}, ...
            mfilename,[tipo '.' nome]);
        dados{linha,3} = valores;
    end
    C.(tipo) = dados;
end

% Monte uma única configuração de referência para cada modelo.
for nome = fieldnames(C).'
    dados = C.(nome{1});
    valores = cellfun(@(v) v(1),dados(:,3),'UniformOutput',false);
    referencia.(nome{1}) = cell2struct(valores,dados(:,1),1);
end
C.f = linspace(0,80,4001).';
C.r = linspace(0,50,501).';
if nargout > 2
    E = roteiro_ferroviario();
end
end

